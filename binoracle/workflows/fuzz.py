"""Fuzzing harness generator.

Two modes, both for AUTHORIZED targets / your own code:
  - libfuzzer: a C harness that feeds fuzzed bytes to a target function.
  - afl: a ready afl-fuzz command line to black-box fuzz the binary via stdin/@@.

This closes the 'no fuzzing' gap at the practical, get-you-started level."""
from __future__ import annotations

from typing import Optional


def libfuzzer_harness(target_func: str = "target_function") -> str:
    return f'''// libFuzzer harness generated by binoracle
// Build: clang -g -O1 -fsanitize=fuzzer,address harness.c target.c -o fuzz_{target_func}
// Run:   ./fuzz_{target_func} -max_len=4096 corpus/
#include <stdint.h>
#include <stddef.h>
#include <string.h>

// TODO: declare / include the real prototype of the function under test.
extern void {target_func}(const unsigned char *data, size_t size);

int LLVMFuzzerTestOneInput(const uint8_t *Data, size_t Size) {{
    // Feed the fuzzed buffer to the target. Adapt the call to the real signature:
    //   - if it takes a C string, NUL-terminate a copy first.
    //   - if it parses a struct/header, map the fields from Data.
    {target_func}(Data, Size);
    return 0;
}}
'''


def afl_command(binary: str, via_stdin: bool = True) -> str:
    target = binary
    inp = "@@" if not via_stdin else ""
    redir = "" if not via_stdin else "  # AFL feeds testcases on stdin"
    argline = f"{target} {inp}".strip()
    return f'''# AFL++ black-box fuzzing of an authorized target
# 1) seed corpus
mkdir -p in out && printf 'A' > in/seed
# 2) (recommended) build with instrumentation if you have source:
#    afl-clang-fast -o {target}.afl target.c
# 3) fuzz (QEMU mode -Q for black-box binaries without source):
afl-fuzz -Q -i in -o out -- {argline}{redir}
'''


def generate_fuzz(binary: str, target_func: Optional[str] = None, mode: str = "afl") -> str:
    if mode == "libfuzzer":
        return libfuzzer_harness(target_func or "target_function")
    return afl_command(binary)
