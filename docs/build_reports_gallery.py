#!/usr/bin/env python3
"""
Build docs/site/reports/index.html — a gallery of all CVE investigation reports.
Runs as part of the GitHub Pages CI step (see .github/workflows/pages.yml).
"""
import os, re, json, html
from pathlib import Path

ROOT    = Path(__file__).parent.parent
REPORTS = ROOT / "reports"
SITE    = ROOT / "docs" / "site" / "reports"

SITE.mkdir(parents=True, exist_ok=True)

_TITLE_RE  = re.compile(r"<title>(.*?)</title>", re.I | re.S)
_BADGE_RE  = re.compile(r'data-confidence="([^"]+)"', re.I)
_SCORE_RE  = re.compile(r'data-cvss="([^"]+)"', re.I)
_SEVERITY_RE = re.compile(r'data-severity="([^"]+)"', re.I)
_CLASS_RE  = re.compile(r'data-vuln-class="([^"]+)"', re.I)


def _parse_report(path: Path) -> dict:
    try:
        text = path.read_text(errors="replace")[:8000]
    except Exception:
        return {}
    cve_id  = re.search(r"CVE-\d{4}-\d+", path.stem, re.I)
    cve_id  = cve_id.group(0).upper() if cve_id else path.stem
    title_m = _TITLE_RE.search(text)
    title   = title_m.group(1) if title_m else cve_id
    conf    = (_BADGE_RE.search(text) or type("", (), {"group": lambda s,n: ""})()).group(1)
    score   = (_SCORE_RE.search(text) or type("", (), {"group": lambda s,n: ""})()).group(1)
    sev     = (_SEVERITY_RE.search(text) or type("", (), {"group": lambda s,n: ""})()).group(1)
    cls     = (_CLASS_RE.search(text) or type("", (), {"group": lambda s,n: ""})()).group(1)
    return {
        "cve_id":    cve_id,
        "title":     title,
        "file":      path.name,
        "confidence": conf or "none",
        "cvss":      score or "",
        "severity":  sev or "",
        "vuln_class": cls or "",
    }


def _conf_color(c: str) -> str:
    return {"confirmed": "#22c55e", "probable": "#38bdf8",
            "inconclusive": "#f59e0b", "not_reproducible": "#6b7280"}.get(c, "#334155")


def _sev_color(s: str) -> str:
    s = s.lower()
    return {"critical": "#ef4444", "high": "#f97316",
            "medium": "#f59e0b", "low": "#22c55e", "none": "#6b7280"}.get(s, "#334155")


reports = []
for p in sorted(REPORTS.glob("*.html")):
    info = _parse_report(p)
    if info:
        reports.append(info)

CONF_ORDER = {"confirmed": 0, "probable": 1, "inconclusive": 2, "not_reproducible": 3, "none": 4}
reports.sort(key=lambda r: (CONF_ORDER.get(r["confidence"], 9), r["cve_id"]))

cards = ""
for r in reports:
    cc  = _conf_color(r["confidence"])
    sc  = _sev_color(r["severity"])
    conf_badge = (f'<span style="background:{cc}22;color:{cc};border:1px solid {cc}44;'
                  f'padding:2px 8px;border-radius:4px;font-size:11px;font-weight:600;'
                  f'text-transform:uppercase;letter-spacing:.05em">{html.escape(r["confidence"])}</span>'
                  if r["confidence"] != "none" else "")
    sev_badge  = (f'<span style="background:{sc}22;color:{sc};border:1px solid {sc}44;'
                  f'padding:2px 8px;border-radius:4px;font-size:11px;font-weight:600">'
                  f'{html.escape(r["severity"].upper())}'
                  f'{" · " + html.escape(r["cvss"]) if r["cvss"] else ""}</span>'
                  if r["severity"] else "")
    cls_badge  = (f'<span style="background:#7c3aed22;color:#a78bfa;border:1px solid #7c3aed44;'
                  f'padding:2px 8px;border-radius:4px;font-size:11px">'
                  f'{html.escape(r["vuln_class"])}</span>'
                  if r["vuln_class"] else "")
    badges = " ".join(b for b in [conf_badge, sev_badge, cls_badge] if b)
    cards += f"""
    <a class="card" href="{html.escape(r['file'])}">
      <div class="card-id">{html.escape(r['cve_id'])}</div>
      <div class="card-badges">{badges}</div>
    </a>"""

